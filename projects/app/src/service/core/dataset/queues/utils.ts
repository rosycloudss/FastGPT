// 团队错误枚举
import { TeamErrEnum } from '@fastgpt/global/common/error/code/team';
// 团队AI积分检查功能
import { checkTeamAIPoints } from '@fastgpt/service/support/permission/teamLimit';
// 用户通知发送功能
import { sendOneInform } from '../../../support/user/inform/api';
// 训练数据锁定控制器
import { lockTrainingDataByTeamId } from '@fastgpt/service/core/dataset/training/controller';
// 通知级别枚举
import { InformLevelEnum } from '@fastgpt/global/support/user/inform/constants';

/**
 * 检查团队AI积分并锁定
 * 
 * 这是队列系统的核心资源管理函数，负责在任务执行前验证团队的AI积分余额，
 * 并在资源不足时采取相应的保护措施。该函数确保系统资源的合理分配和使用，
 * 防止团队超额消费导致的系统不稳定。
 * 
 * 主要功能：
 * 
 * 1. 积分余额检查：
 *    - 实时查询团队的AI积分余额
 *    - 验证是否满足当前任务的资源需求
 *    - 支持多种积分类型和计费模式
 *    - 考虑预留积分和缓冲机制
 * 
 * 2. 资源锁定机制：
 *    - 在积分不足时自动锁定相关训练数据
 *    - 防止无效任务继续消耗系统资源
 *    - 支持细粒度的锁定策略和范围
 *    - 提供锁定状态的查询和管理接口
 * 
 * 3. 通知与告警：
 *    - 积分不足时自动发送通知给团队管理员
 *    - 支持多种通知渠道（邮件、短信、系统消息等）
 *    - 可配置的通知频率和内容模板
 *    - 防止重复通知的去重机制
 * 
 * 4. 状态管理与恢复：
 *    - 记录积分检查的历史状态
 *    - 支持积分充值后的自动解锁
 *    - 提供手动解锁和状态重置功能
 *    - 维护系统状态的一致性
 * 
 * 处理流程：
 * 
 * 1. 积分查询阶段：
 *    - 根据teamId查询当前积分余额
 *    - 获取团队的积分使用历史和趋势
 *    - 计算预估的任务消耗成本
 *    - 判断是否满足执行条件
 * 
 * 2. 决策判断阶段：
 *    - 比较可用积分与预估消耗
 *    - 考虑系统预留和安全边际
 *    - 评估任务的优先级和重要性
 *    - 做出继续或暂停的决策
 * 
 * 3. 保护措施执行：
 *    - 积分充足时：返回true，允许任务继续
 *    - 积分不足时：执行锁定和通知流程
 *    - 记录决策过程和相关日志
 *    - 更新团队的资源使用状态
 * 
 * 4. 通知与反馈：
 *    - 发送积分不足的通知消息
 *    - 提供充值和解锁的操作指引
 *    - 记录通知发送的状态和结果
 *    - 支持通知的重试和失败处理
 * 
 * 技术实现特点：
 * - 原子性操作：确保检查和锁定的原子性
 * - 并发安全：支持多线程并发访问
 * - 性能优化：缓存机制减少数据库查询
 * - 容错处理：网络异常和服务不可用的处理
 * - 监控友好：详细的性能指标和状态日志
 * 
 * 安全考虑：
 * - 防止积分余额的并发修改冲突
 * - 避免恶意的资源消耗攻击
 * - 确保积分计算的准确性和一致性
 * - 保护敏感的财务和计费信息
 * 
 * 性能优化：
 * - 积分查询的缓存策略
 * - 批量操作减少数据库访问
 * - 异步通知避免阻塞主流程
 * - 智能的重试和退避机制
 * 
 * 注意事项：
 * - 该函数可能会修改数据库状态
 * - 通知发送可能存在延迟或失败
 * - 需要定期清理过期的锁定状态
 * - 积分计算需要考虑汇率和折扣
 * 
 * @param {string} teamId - 团队的唯一标识符
 *   - 必须是有效的MongoDB ObjectId格式
 *   - 用于查询团队的积分余额和配置信息
 *   - 作为资源隔离和权限控制的依据
 * 
 * @returns {Promise<boolean>} 返回积分检查的结果
 *   - true: 积分充足，可以继续执行任务
 *   - false: 积分不足，任务应该暂停或终止
 * 
 * @throws {Error} 在以下情况下可能抛出异常：
 *   - 数据库连接失败或查询超时
 *   - teamId格式无效或团队不存在
 *   - 积分服务不可用或响应异常
 *   - 通知服务异常或配置错误
 * 
 * @example
 * ```typescript
 * // 在任务执行前检查积分
 * try {
 *   const hasEnoughPoints = await checkTeamAiPointsAndLock('60f1b2b3c4d5e6f7g8h9i0j1');
 *   
 *   if (hasEnoughPoints) {
 *     console.log('积分充足，开始执行任务');
 *     // 继续执行任务逻辑
 *   } else {
 *     console.log('积分不足，任务已暂停');
 *     // 处理积分不足的情况
 *   }
 * } catch (error) {
 *   console.error('积分检查失败:', error);
 *   // 处理异常情况
 * }
 * ```
 * 
 * @example
 * ```typescript
 * // 在队列处理循环中使用
 * for (const task of tasks) {
 *   if (!(await checkTeamAiPointsAndLock(task.teamId))) {
 *     console.log(`团队 ${task.teamId} 积分不足，跳过任务`);
 *     continue;
 *   }
 *   
 *   // 执行任务处理逻辑
 *   await processTask(task);
 * }
 * ```
 */
export const checkTeamAiPointsAndLock = async (teamId: string) => {
  try {
    // 检查团队AI积分是否充足
    await checkTeamAIPoints(teamId);
    return true;
  } catch (error: any) {
    // 如果是积分不足错误
    if (error === TeamErrEnum.aiPointsNotEnough) {
      // 发送通知并锁定数据
      try {
        // 发送紧急通知给团队
        sendOneInform({
          level: InformLevelEnum.emergency,
          templateCode: 'LACK_OF_POINTS',
          templateParam: {},
          teamId
        });
        console.log('余额不足，暂停知识库处理');
        // 锁定该团队的所有训练数据
        await lockTrainingDataByTeamId(teamId);
      } catch (error) {
        // 忽略通知发送或锁定过程中的错误
      }
    }
    return false;
  }
};
